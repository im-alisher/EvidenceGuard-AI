"""Optional local Streamlit viewer for versioned experiment artifacts."""

from __future__ import annotations

import json

import streamlit as st

from evidenceguard.errors import ReportError
from evidenceguard.reporting import parse_run_artifact, render_markdown

st.set_page_config(
    page_title="EvidenceGuard AI runs",
    page_icon=None,
    layout="wide",
)

st.title("EvidenceGuard AI run viewer")
st.caption(
    "Local artifact inspection only. No benchmark results are bundled, and "
    "missing sections are unmeasured rather than zero-valued."
)

uploaded = st.file_uploader("Upload a JSON run artifact", type=["json"])
if uploaded is None:
    st.info("Select an artifact generated by `python -m evidenceguard.experiments`.")
    st.stop()

try:
    payload = json.loads(uploaded.getvalue().decode("utf-8"))
    artifact = parse_run_artifact(payload)
except (UnicodeDecodeError, json.JSONDecodeError, ReportError) as exc:
    st.error(f"Could not read artifact: {exc}")
    st.stop()

metadata_columns = st.columns(5)
metadata_columns[0].metric("Experiment", artifact.name)
metadata_columns[1].metric("Seed", artifact.seed)
metadata_columns[2].metric("Dataset", artifact.dataset_name)
metadata_columns[3].metric("Split", artifact.split)
metadata_columns[4].metric("Retriever", artifact.retriever_name or "not recorded")

retrieval = artifact.retrieval
if retrieval is not None:
    st.subheader("Retrieval")
    st.dataframe(list(retrieval["aggregates"]), hide_index=True)
    skipped = retrieval.get("skipped_query_ids", [])
    if skipped:
        st.warning(f"{len(skipped)} query item(s) lacked positive relevance judgments.")
    st.caption("Retrieval metrics are not answer accuracy or evidence sufficiency.")

decisions = artifact.decisions
if decisions is not None:
    st.subheader("Decisions")
    metrics = decisions["metrics"]
    columns = st.columns(4)
    columns[0].metric("Coverage", f"{metrics['coverage']:.1%}")
    columns[1].metric("Selective risk", f"{metrics['selective_risk']:.1%}")
    columns[2].metric("Abstention rate", f"{metrics['abstention_rate']:.1%}")
    columns[3].metric("Examples", metrics["total_count"])
    st.dataframe(
        [{"metric": key, "value": value} for key, value in metrics.items()],
        hide_index=True,
    )

calibration = artifact.calibration
if calibration is not None:
    st.subheader("Calibration")
    columns = st.columns(3)
    columns[0].metric("Brier score", f"{calibration['brier_score']:.4f}")
    columns[1].metric(
        "Expected calibration error",
        f"{calibration['expected_calibration_error']:.4f}",
    )
    columns[2].metric("Answered", calibration["count"])
    if calibration.get("bins"):
        st.dataframe(list(calibration["bins"]), hide_index=True)

markdown_report = render_markdown(artifact)
with st.expander("Generated Markdown report", expanded=False):
    st.markdown(markdown_report)
st.download_button(
    "Download Markdown report",
    data=markdown_report.encode("utf-8"),
    file_name=f"{artifact.name}-report.md",
    mime="text/markdown",
)

with st.expander("Validated JSON payload", expanded=False):
    st.json(artifact.to_dict())
